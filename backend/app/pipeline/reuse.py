"""Reusing verdicts: a cached verdict in a new answer language, and the spoken answer.

Used by the full pipeline (tier 2 hits, audio after DONE) and by the API's tier 1 path, where the same
photo or video comes back with a caption in another language (acceptance case 3): the caption decides
the answer language (caption_language), the verdict is translated once and stored, and the audio for
the new language is generated by a "speak" job.
"""
from __future__ import annotations

import asyncio
import logging
import os
from typing import Any

from app.agents import composer
from app.intake.language import caption_language, same_language
from app.llm import LLM, StageFailed
from app.models import AnswerText, CheckResult, ClaimResult, NonCheckableType
from app.observability.logging import log_event
from app.output import tts
from app.pipeline import stub
from app.pipeline.progress import CHECKS
from app.pipeline.results import VERDICTS, cached_result, claim_result_from_doc, lang_key
from app.settings import get_settings
from app.store import Store

log = logging.getLogger(__name__)


async def in_language(store: Store, llm: LLM, verdict: dict[str, Any], language: str, script: str) -> ClaimResult:
    """The verdict's answer in `language`; translated once from the English answer and stored if missing."""
    answers = verdict.get("answers") or {}
    if not any(same_language(k, language) for k in answers):
        english = AnswerText.model_validate(answers.get(verdict.get("answer_en_key") or "en")
                                            or next(iter(answers.values())))
        try:
            native = await composer.translate(llm, english, language, script)
            answers = {**answers, lang_key(language): native.model_dump(mode="json")}
            await store.set(VERDICTS, verdict["verdict_id"], {"answers": answers}, merge=True)
            verdict = {**verdict, "answers": answers}
        except StageFailed as e:
            log_event(log, "translation failed", logging.WARNING, reason=str(e)[:300])
    return claim_result_from_doc(verdict, language)


async def tier1_answer(store: Store, llm: LLM, check_id: str, hit: dict[str, Any], caption: str | None
                       ) -> CheckResult:
    """A tier 1 hit, answered in the caption's language when the user wrote one in another language."""
    result = cached_result(check_id, hit)
    found = caption_language(caption)
    if not found or same_language(found[0], result.content_language):
        return result
    language, script = found
    if result.non_checkable_type:
        nct = result.non_checkable_type.value if isinstance(result.non_checkable_type, NonCheckableType) \
            else str(result.non_checkable_type)
        return result.model_copy(update={"content_language": language,
                                         "non_checkable_message": stub.non_checkable_message(nct, language)})
    claims = list(await asyncio.gather(*(in_language(store, llm, v, language, script) for v in hit["verdicts"])))
    if not all(same_language(c.answer.language, language) for c in claims):
        # A translation failed: answer in the cached language rather than label one language and show another.
        return result
    return result.model_copy(update={"claims": claims, "content_language": language})


def tts_enabled() -> bool:
    """Off in LLM_MODE=fake (tests, offline UI) and when TTS_ENABLED=0."""
    return get_settings().llm_mode != "fake" and os.environ.get("TTS_ENABLED", "1") != "0"


def needs_audio(result: CheckResult) -> bool:
    return tts_enabled() and any(not c.audio_url and c.answer.audio_script.strip() for c in result.claims)


async def speak(store: Store, check_id: str, result: CheckResult) -> CheckResult:
    """Spoken answer in the answer language for each claim that has none yet (cache hits reuse it).
    Gemini TTS takes 18-24 s per answer (Oct 7), so this runs after the text answer is DONE."""
    todo = [i for i, c in enumerate(result.claims) if not c.audio_url and c.answer.audio_script.strip()]
    if not todo or not tts_enabled():
        return result
    await store.set(CHECKS, check_id, {"result": {**result.model_dump(mode="json"), "audio_pending": True}},
                    merge=True)

    async def one(i: int) -> tuple[int, str | None]:
        c = result.claims[i]
        try:
            mp3 = await tts.synthesize(c.answer.audio_script, c.answer.language)
            await tts.store_audio(c.verdict_id, c.answer.language, mp3)
        except StageFailed as e:
            log_event(log, "tts failed", logging.WARNING, reason=str(e)[:300])
            return i, None
        url = tts.audio_url(c.verdict_id, c.answer.language)
        doc = await store.get(VERDICTS, c.verdict_id) or {}
        answers = dict(doc.get("answers") or {})
        key = next((k for k in answers if same_language(k, c.answer.language)), lang_key(c.answer.language))
        answers[key] = {**answers.get(key, c.answer.model_dump(mode="json")), "audio_url": url}
        await store.set(VERDICTS, c.verdict_id, {"answers": answers}, merge=True)
        return i, url

    urls = dict(await asyncio.gather(*(one(i) for i in todo)))
    claims = [c.model_copy(update={"audio_url": urls.get(i) or c.audio_url}) for i, c in enumerate(result.claims)]
    result = result.model_copy(update={"claims": claims, "audio_pending": False})
    await store.set(CHECKS, check_id, {"result": result.model_dump(mode="json")}, merge=True)
    return result


async def speak_check(store: Store, check_id: str) -> None:
    """The "speak" job: audio for a check that is already DONE (a tier 1 hit in a new language)."""
    doc = await store.get(CHECKS, check_id)
    if doc and doc.get("result"):
        await speak(store, check_id, CheckResult.model_validate(doc["result"]))
